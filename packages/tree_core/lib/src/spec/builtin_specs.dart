## 边界与异常处理

- **升级 hard 触发（任一命中）**：需要分工协作 / 多角色并行 / 需要正式会议 / 架构级影响 / 方案分歧大 / 涉及高危操作（安全、数据迁移、不可逆）→ 停下升级 hard-task。
- **降级 easy 触发**：执行中发现其实单文件即可完成（其余 todo 作废或已收敛）→ 降级 easy-task 直接完成，并在汇报中说明判型变化。
