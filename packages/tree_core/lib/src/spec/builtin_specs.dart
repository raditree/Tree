```

## 风险评估框架

- **概率 × 影响矩阵**：对每个已识别风险标注概率（高/中/低）与影响（高/中/低）；
  概率高×影响高 → 必须先定缓解措施再实施；写入决策记录的"风险与缓解"。
- **高危操作清单（命中即触发用户确认）**：
  - 数据迁移 / 批量删除 / 覆盖既有数据；
  - 安全相关（鉴权/加密/权限变更）；
  - 兼容性破坏（对外接口/存储格式/协议变更）；
  - 不可逆变更（删除源码/历史/配置无法恢复）。
- **高危确认单四要素**（`ask_user_question` 时必须给全）：
  1. 操作内容：具体要执行什么；
  2. 影响范围：波及哪些数据/模块/用户；
  3. 回滚方案：出问题如何恢复；
  4. 是否继续：请用户明确决策。

## 边界与异常处理

- **问题过大应拆分**：一个 hard-task 装不下时，按模块或阶段拆成多个 hard-task 分别处理，共享同一份决策记录与边界文档。
- **可降级**：侦察或会议中若发现不满足 hard 判据（实际只是多文件改动、无架构影响、单人可收敛）→ 降级 complex-task 走其流程，并保留 `recon.md` 与工作空间文档作为输入。
- **方案评审不通过**：按“流水线阶段标准”末尾路径处理（迭代 ≤2 轮 → 升级用户）。
- **实施中发现方案不可行**：停下 → 回退到方案设计阶段 → 在决策记录追加“实施反馈”与原因 → 重新评审，禁止边做边大幅偏离已评审方案。
- **高危操作被用户拒绝**：记录决策（用户选择），调整方案或终止任务，同样走 Spec 沉淀闭环。
- **top agent 不得不亲自处理业务文件**：在 `task.md`/`checklist.md` 记录原因、范围、补验安排，并优先交回成员维护。
- **成员超时/失败**：先读 `agentspace/{member_id}/.self/activity.log` 定位；给修正指令重试一次；仍失败则收回或换人，交接已完成部分。

