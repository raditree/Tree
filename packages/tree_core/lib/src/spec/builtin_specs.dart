## 该类任务规范

- **会议 ≠ 开工**：收到"会议 / 讨论 / 出方案"性质的消息，一律先只讨论；
  没有收到明确的 `message send_message`"开始执行"指令前，**禁止**任何文件写入、命令执行、自行开工。
- **发言结构化**：按发言模板四要素（方案思路/理由与利弊/风险/前置问题），简明不冗长。
- **决策闭环**：leader 必须明确给出最终选型与执行指令，不能把会议悬空；成员收到指令后再动手。
- **产出可追溯**：方案与决策理由写入工作空间文档（`.self/`）。
- **发言轮次收敛**：每个议题成员发言 ≤ 2 轮；仍无共识 → 走"边界与异常处理"的收敛机制。
- **可结合 hard-task**：hard 流程中的"团队会议"阶段遵循本 Spec；会议结束后回到 hard-task
  流水线（需求→方案→评审→实现→测试→交付）。
- 会议期间如需了解现状，可用 `read` 读取相关文件辅助判断，但**不得修改**。

