## 工作流（workflow）

1. **会议召集（leader）**：明确会议主题与目标、参会成员、需要的背景材料，
   用 `message send_message`（全员则 `message broadcast`）邀请相关成员参会，消息按"会议召集消息模板"撰写，
   **明确标注"本次为会议讨论，请只给方案/意见，禁止改代码、跑命令、派活"**。
2. **成员发言（成员）**：收到会议消息后，只围绕主题按"成员发言模板"给出：
   方案思路、理由与利弊、风险点、所需前置信息。
   **严禁**调用 write/edit/terminal 等落地工具，也不得提前自行开工。
3. **方案汇总（leader）**：收集各成员方案，按"方案比较矩阵模板"比较选型，
   记录选择理由（写入工作空间方案文档，配合 hard-task 的决策记录模板）。
4. **定案与分工（leader）**：方案确定后，用 `team update_member` 明确分工，
   再用 `message send_message` 发**明确的执行指令**（注明"开始执行任务：xxx"）。
5. **进入执行**：收到明确执行指令后，成员方可按分工开始落地（写入/修改/验证）。
6. **会议纪要**：将结论、选型理由、分工与待办按"会议纪要模板"沉淀到
