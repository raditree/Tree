## 判型确认（开工前必查）

**任一命中即走 hard**：

| # | 判据 | 判定说明 |
|---|------|----------|
| 1 | 架构级、框架级变更 | 动分层结构/引入或更换框架/改核心抽象 |
| 2 | 新领域无经验 | 团队对该技术域无既有实践，方案需要探索 |
| 3 | 高不确定、需多方案比较 | 候选方案 ≥2 且优劣不明显，需评审定夺 |
| 4 | 高危操作 | 安全/性能/数据迁移/兼容性/不可逆变更 |
| 5 | 需要团队分工协作 | 多角色并行、跨模块多人协作、需要正式会议决策 |
| 6 | 用户明示 | "重新设计 / 大重构 / 企业级 / 谨慎处理" |

**与 complex 的边界**：多文件改动但无架构影响、单人可收敛、方案唯一明确 → complex 即可，不升 hard；
需要分工协作、多角色并行、正式会议决策 → hard 专属，不走 complex；
判型存疑时宁可上调（hard 可降级，complex 硬撑风险更高）。

## 工作流（workflow）

### 阶段 0：判型与 Spec 检索

1. 初始化 todo：初始 todo 可仅包含基本工作流，到每个阶段时要求**先细化再执行**。
2. 按上方判型表确认 hard。
3. 对照系统提示词里的「Spec 索引」：
   - 命中适用 Spec → `spec select`（**直接返回全文**），作为 hard 约束执行；
   - 仅模糊命中 / 无命中 → 走本企业级流水线；
   - 若发现实际只需单人、无架构影响 → 按边界降级 complex，并保留已建文档作为输入。
4. 用 `set_todo_list` 建立全任务计划，包含各阶段评审点。

### 阶段 1：侦察（Recon）

**top agent 亲自执行**，动手开会前必须完成系统侦察，禁止凭想象立目标、定议程。

1. 创建 `agentspace/.hard/{task_id}/`（`task_id` 建议为 `YYYYMMDD-{task_slug}`）。
2. 侦察维度（至少覆盖）：
   - **边界侦察**：`grep` 相关入口文件、模块、接口、上下游调用链及侦察范围。
   - **代码侦察**：`read` 数据模型、配置、测试，梳理分层、调用链、数据流、现有模式与约定、技术债。
   - **环境侦察**：`terminal` 确认构建/测试/部署命令、依赖与版本、运行环境（是否有虚拟环境）、git 工作区与分支状态、CI/发布约束。
   - **历史侦察**：用系统提示词里的 Spec 索引找历史 Spec，用 `spec select` 取全文查决策记录；查近期相关提交、历史遗留问题、既往尝试与失败原因。
   - **约束侦察**：明确不可改范围、对外接口/存储格式/协议兼容性、合规与安全要求、外部依赖。
   - **领域侦察**（判据 2 命中时必做）：对无经验技术域做调研，收集候选方案、参考实现、行业实践与坑。
3. **产出**：侦察笔记写入 `agentspace/.hard/{task_id}/recon.md`，至少含：
   - 现状与架构概览；
   - 涉及面（文件/模块/接口/数据/依赖清单）；
   - 约束与不可动范围；
   - 候选方向与初步对比（如适用）；
   - 未知项、初始风险、待决策问题；
   - 建议的会议议程与参会角色。
4. 侦察发现判型有变（降级 complex / 需拆分多个 hard）→ 按边界与异常处理执行。

### 阶段 2：初始化 hard 工作空间与上下文

1. 基于 `recon.md` 补全 hard 工作空间，**至少**包含：
   - `goal.md`：背景、目标、范围、明确不做项、约束、验收标准、初始风险、干系人。
   - `spec.md`：Spec 检索结果、选中 Spec、规范约束、参考文档。
   - `task.md`：WBS/todo、角色与成员、文件所有权、接口约定、依赖、里程碑、评审点、成员时间预算。
   - `checklist.md`：阶段准入准出、测试/回归、高危确认、验收三问、交付检查项。
   - `meeting/`：至少一个会议文件，如 `meeting/01-kickoff.md`；后续可 `meeting/02-review.md` 等。
   - `recon.md`：阶段 1 侦察笔记（已在阶段 1 生成）。
2. 可选但推荐：`decisions/ADR.md`、`artifacts/`、`reports/`。
3. 明确记录：本任务所有过程产物写入该工作空间，便于追溯与中断恢复。

### 阶段 3：会前上下文与会议议程

1. **top agent 召开会议前必须先明确任务上下文**：
   - `read` `recon.md`、`goal.md`、`spec.md`、`task.md`、`checklist.md`；
   - 补读关键代码、接口、依赖、测试、历史决策；
   - 形成"会前上下文"：现状、目标、范围、不做项、约束、已知风险、未知项、候选方向。
2. **确立会议议程**并写入 `meeting/01-kickoff.md`，议程至少包含：
   - 背景与目标；
   - 范围与不做项；
   - 约束与验收标准；
   - 已知风险与待决策问题；
   - 候选方案/备选方向；
   - 参会角色与职责；
   - 期望产出；
   - 时间盒与决策规则。
3. `team list_members` 查看成员拓扑；`team update_member` 激活架构/前端/后端/测试/安全等角色并设置职责。
4. 用 `message send_message`（或 `message broadcast`）发送会议通知，附议程、会前上下文、准备材料与期望产出。

### 阶段 4：团队会议与方案评审

1. 严格遵循 **team-meeting** Spec：会议期间只讨论、只产出方案，禁止落地实现。
2. 各成员按角色给出方案；top agent 汇总方案、按选型矩阵比较。
3. 用决策记录模板（ADR）记录选型理由，写入 `meeting/xx.md` 或 `decisions/ADR.md`。
4. 方案评审通过后才准进入实现；评审不通过：迭代设计 → 复审（最多 2 轮）→ 仍无共识 → `ask_user_question` 升级用户决策。

### 阶段 5：任务分解与分工派活

1. 基于 `task.md` 拆解 todo：每项可独立验证，明确完成判据、依赖、影响面、回归范围、文件所有权。
2. **文件所有权原则**：同一文件同一时刻只允许一个负责人；多人需改同一文件 → 串行化或拆分职责。
3. **top agent 职责边界（防踩坑）**：
   - top agent 默认**不直接 `edit`/`write` 业务文件**；
   - top agent 只维护 `agentspace/.hard/{task_id}/` 下的管理文档（recon/goal/spec/task/checklist/meeting/ADR/验收记录）并做协调、决策、验收；
   - 仅当成员失败回收、紧急修复等特殊情况，top agent 才可亲自处理业务文件，且必须在 `task.md`/`checklist.md` 记录原因、范围、后续补验，并优先交接回成员。
4. 用 `message send_message` 派活，**派活信息四要素**：目标 / 输入（相关文件与上下文）/ 验收标准 / 期望产出物。
5. **给成员较长执行时间**：
   - 派活时显式给出时间预算（建议 ≥30–60 分钟或按复杂度上浮）；
   - 允许成员内部召集子团队、开子会议、走其企业流程；
   - 使用 `wait_for` 长超时等待交付，期间不频繁催促；成员按里程碑汇报即可。
6. 需要全员并行时用 `message broadcast`（仅直属成员）；激活成员数量适中：1–3 个为宜，按需激活，勿全员开工。

### 阶段 6：实现与成员产出验收

1. 成员按 todo 执行，每完成里程碑更新其活动日志与产物，并向 top agent 汇报。
2. top agent 必须验收成员产出，不能直接采信：
   - 统一工作目录下直接 `read` 其活动日志 `agentspace/{member_id}/.self/activity.log`（可 grep `[done]`/`[tool]`/`[error]` 定位）；
   - 检查产物文件与 `task.md`、`checklist.md` 要求。
3. **验收三问**：
   - 是否达到指派时写明的验收标准？
   - 是否引入回归（改动范围外是否被波及）？
   - 相关文档/配置是否同步更新？
4. 验收不通过 → 先 `read` 日志定位失败原因 → `message send_message` 给出修正指令重试一次 → 仍失败则收回由 top agent 自做或换成员接手；交接时说明已完成部分。

### 阶段 7：测试（整个流水线最重要的一环）

1. 每阶段有自测；最终必须全量验证：
   - 构建；
   - 全量测试；
   - 回归测试；
   - 关键路径人工核对；
   - 影响面核对；
   - 文档/配置同步检查。
2. 测试报告写入 `agentspace/.hard/{task_id}/reports/` 或 `checklist.md`，逐项勾选。
3. 测试不通过：定位失败项 → 回退对应 todo 修复 → 重验；连续 2 轮不过 → 向用户如实汇报失败详情与下一步建议。

### 阶段 8：交付与沉淀

1. 按“汇报模板”向用户交付，如实呈现遗留项与风险。
2. **强制** `spec create` 沉淀本次经验（缺失则任务未闭环）。
3. 将最终 `recon.md`、`goal.md`、`task.md`、`checklist.md`、会议记录、ADR、测试报告归档到 hard 工作空间。

## 该类任务规范

- **必须过会议讨论阶段**：hard 任务禁止直接动手实现，先开会定方案。
- **先侦察再开会**：top agent 必须先完成 Recon 并写 `recon.md`，再初始化工作空间、写议程、召集会议。
- **工作空间必建**：`agentspace/.hard/{task_id}/` 至少含 `recon.md`、`goal.md`、`meeting/xx.md`、`spec.md`、`task.md`、`checklist.md`。
- **会议前必须有上下文与议程**：top agent 先写 `meeting/01-kickoff.md` 的会前上下文与议程，再召集会议。
- **top agent 不抢业务文件**：top agent 默认只写管理文档与协调验收；亲自处理业务文件必须记录原因并补验。
- **分工明确**：`task.md` 必须写清角色、文件所有权、接口约定、依赖与时间预算。
- **成员长时执行**：派活给足时间，允许成员带子团队、开会、走企业流程；`wait_for` 长超时，不频繁打断。
- **流水线每阶段有产出物与评审**：阶段产物写入 hard 工作空间，由团队评审，不跳过任何阶段。
- **高危必确认**：不可逆/高风险操作先 `ask_user_question`，禁止未确认执行破坏性命令。
- **末尾必补 Spec**：`spec create` 是本任务闭环的最后强制步骤，无论成功与否。
- **方案比较记录理由**：为什么选 A 不选 B，按决策记录模板写进会议/ADR 文档。
- **全任务 todo 计划**：用 `set_todo_list` 建立，各阶段评审点作为独立 todo 项跟踪。

## 流水线阶段标准

| 阶段 | 产出物 | 评审要点 | 准出条件 |
|------|--------|----------|----------|
| 侦察 | `recon.md`（现状/涉及面/约束/未知项/初始风险） | 完整性、准确性、是否覆盖代码/环境/历史/约束/领域 | 涉及面与约束清单可追溯、未知项明确 |
| 需求分析 | `goal.md`（用户目标/功能点/不做项/验收标准） | 完整性/一致性/可验证性 | 验收标准可测、无歧义 |
| 方案设计 | `meeting/xx.md` + ADR（模块划分/接口约定/数据流/风险） | 可行性/风险/成本/兼容性/可回滚 | 至少 2 个候选比较后定稿 |
| 方案评审 | 评审结论（团队评审记录） | 是否达成共识、风险是否可接受 | 评审通过才准实现 |
| 实现 | 成员产物 + 自测记录 + `task.md` 状态 | 按设计实现/编码规范/自测通过 | 偏离设计处已在决策记录追加说明 |
| 测试 | 测试报告（全量 + 关键路径 + 回归） | 覆盖影响面、回归无意外 | 全部通过（或遗留项经用户确认） |
| 交付 | 交付汇报（含验证结果与遗留项） | 汇报完整性 | 用户已知悉结果与风险 |

**评审不通过路径**：迭代设计 → 复审（最多 2 轮）→ 仍无共识 → `ask_user_question` 升级用户决策。

## 决策记录模板（ADR 风格）

写入 `meeting/xx.md` 或 `decisions/ADR.md`，供追溯：

```
