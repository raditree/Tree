## 该类任务规范

- **单一口径**：协议细节只认指南与代码，本规范与指南冲突时以指南/代码为准，并把冲突报告出来（别自作主张改口径）。
- **不改核心协议**：插件侧适配；发现核心确有缺陷，如实报告并另提任务。
- **不越权**：只动自己的插件文件与其 `plugins.yaml` 条目；不改他人插件、不删别人的订阅与配置
  （破坏性操作先 `ask_user_question`）。
- **远端不在远端落地**：插件必须在本机；远端侧一律走派活与验收，不"先写了再说"。
- **只用标准库、可绝对路径启动**：便于用户直接拷贝使用、不依赖 cwd。
- **fail-open 是设计承诺**：插件异常/未响应不得阻塞生成；插件侧出错记日志并放行原数据，不静默吞掉。
- **双证据**：自测（可回归）+ 真核心端到端（可观察），缺一不算交付。
- **派活要可验收**：给本机 agent 的需求必须自带验收标准，否则交付无法判合格。

